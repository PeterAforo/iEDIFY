// Dev tool: regenerates resources/views/partials/africa-defs.twig from
// Natural Earth 1:110m admin-0 countries (public domain, naturalearthdata.com).
// Usage: node bin/generate-africa-svg.mjs
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';

const SOURCE = 'https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_110m_admin_0_countries.geojson';
const WIDTH = 500;

const geo = await (await fetch(SOURCE)).json();
const rings = [];
for (const feature of geo.features) {
  if (feature.properties.CONTINENT !== 'Africa') continue;
  const { type, coordinates } = feature.geometry;
  const polygons = type === 'Polygon' ? [coordinates] : coordinates;
  for (const polygon of polygons) rings.push(polygon[0]);
}

// Plain equirectangular: Africa straddles the equator, so distortion is minimal.
let minX = Infinity, maxX = -Infinity, minY = Infinity, maxY = -Infinity;
const projected = rings.map((ring) => ring.map(([lon, lat]) => {
  const x = lon;
  const y = -lat;
  minX = Math.min(minX, x); maxX = Math.max(maxX, x);
  minY = Math.min(minY, y); maxY = Math.max(maxY, y);
  return [x, y];
}));
const scale = WIDTH / (maxX - minX);
const height = Math.round((maxY - minY) * scale);
const d = projected.map((ring) => ring.map(([x, y], i) =>
  `${i ? 'L' : 'M'}${((x - minX) * scale).toFixed(1)} ${((y - minY) * scale).toFixed(1)}`).join('') + 'Z').join('');

// Accra HQ pin position in the same projection.
const pin = { x: ((-0.187 - minX) * scale).toFixed(1), y: ((-5.6037 - minY) * scale).toFixed(1) };

const twig = `{# Generated by bin/generate-africa-svg.mjs from Natural Earth (public domain). Do not edit by hand. #}
{% macro viewbox() %}0 0 ${WIDTH} ${height}{% endmacro %}
{% macro hq_x() %}${pin.x}{% endmacro %}
{% macro hq_y() %}${pin.y}{% endmacro %}
{% macro defs() %}
<svg class="svg-defs" width="0" height="0" aria-hidden="true" focusable="false">
    <defs>
        <path id="africa-shape" d="${d}"/>
        <clipPath id="africa-clip"><use href="#africa-shape"/></clipPath>
        <pattern id="africa-dots" width="9" height="9" patternUnits="userSpaceOnUse"><circle cx="4.5" cy="4.5" r="2"/></pattern>
    </defs>
</svg>
{% endmacro %}
`;
writeFileSync(join(process.cwd(), 'resources', 'views', 'partials', 'africa-defs.twig'), twig);
console.log(`africa-defs.twig written: ${rings.length} rings, viewBox 0 0 ${WIDTH} ${height}, ${d.length} chars`);
